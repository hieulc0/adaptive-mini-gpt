"""Autonomous Curriculum Selector and Continual Learning Controller (M26 Phase 3).

Implements bounded, evidence-driven curriculum selection across multiple capability
domains (Arithmetic, Language, Logic, Retention).

Compares:
  A. Fixed Round-Robin Curriculum.
  B. Largest Measured Skill-Gap Selection.
  C. Learning-Progress and Retention-Aware Selection.

Guarantees:
  - Candidates train in isolated branches without mutating base checkpoints.
  - Independent validation data guides selection, while final test splits remain sealed.
  - Predicts expected skill gain and retention drift for empirical calibration.
  - Replay buffering is dynamically scheduled when positive drift is detected.
"""

from __future__ import annotations

import logging
from dataclasses import asdict, dataclass, field
from enum import Enum
from typing import Any

from adaptive_mini_gpt.evaluation.multi_domain import DomainType

logger = logging.getLogger(__name__)


class CurriculumStrategy(str, Enum):
    """Supported curriculum selection policies for comparative evaluation."""

    ROUND_ROBIN = "round_robin"
    LARGEST_GAP = "largest_gap"
    PROGRESS_AND_RETENTION_AWARE = "progress_and_retention_aware"


class InterventionType(str, Enum):
    """Types of learning interventions the controller can propose."""

    FOCUSED_FINETUNE = "focused_finetune"
    INTERLEAVED_MULTIDOMAIN = "interleaved_multidomain"
    REPLAY_STABILIZED = "replay_stabilized"
    CAPACITY_EXPANSION_PROPOSAL = "capacity_expansion_proposal"


@dataclass
class CurriculumProposal:
    """A bounded, actionable training experiment proposal generated by the selector."""

    cycle_index: int
    strategy: CurriculumStrategy
    target_domain: DomainType
    intervention: InterventionType
    sampling_ratios: dict[str, float]
    replay_ratio: float
    budget_epochs: int
    learning_rate: float
    batch_size: int
    rationale: str
    predicted_gain: float
    predicted_retention_drift: float
    requires_human_approval: bool = False

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        data["strategy"] = self.strategy.value
        data["target_domain"] = self.target_domain.value
        data["intervention"] = self.intervention.value
        return data


@dataclass
class CycleResult:
    """Outcome record of an executed curriculum proposal."""

    cycle_index: int
    proposal: CurriculumProposal
    pre_metrics: dict[str, float]
    post_metrics: dict[str, float]
    observed_gain: float
    observed_retention_drift: float
    gain_prediction_error: float
    is_promoted_to_candidate: bool
    rejection_reason: str | None = None

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        data["proposal"] = self.proposal.to_dict()
        return data


class CurriculumSelector:
    """Minimal autonomous curriculum selector evaluating skill gaps and retention trade-offs."""

    def __init__(
        self,
        strategy: CurriculumStrategy = CurriculumStrategy.PROGRESS_AND_RETENTION_AWARE,
        target_accuracy: float = 0.90,
        max_regression_tolerance: float = 0.10,
        default_budget_epochs: int = 12,
        default_lr: float = 3e-4,
    ) -> None:
        self.strategy = strategy
        self.target_accuracy = target_accuracy
        self.max_regression_tolerance = max_regression_tolerance
        self.default_budget_epochs = default_budget_epochs
        self.default_lr = default_lr
        self.cycle_history: list[CycleResult] = []

    def select_next_experiment(
        self,
        cycle_index: int,
        current_metrics: dict[str, float],
        retention_drift: float = 0.0,
    ) -> CurriculumProposal:
        """Propose the next bounded learning experiment based on the active strategy.

        Args:
            cycle_index: 1-indexed sequential cycle count.
            current_metrics: Dictionary of domain -> validation accuracy (0.0 to 1.0).
            retention_drift: Current delta in cross-entropy loss on pretraining prose.
        """
        if self.strategy == CurriculumStrategy.ROUND_ROBIN:
            return self._select_round_robin(cycle_index, current_metrics, retention_drift)
        elif self.strategy == CurriculumStrategy.LARGEST_GAP:
            return self._select_largest_gap(cycle_index, current_metrics, retention_drift)
        elif self.strategy == CurriculumStrategy.PROGRESS_AND_RETENTION_AWARE:
            return self._select_progress_and_retention_aware(cycle_index, current_metrics, retention_drift)
        else:
            raise ValueError(f"Unknown curriculum strategy: {self.strategy}")

    def _select_round_robin(
        self,
        cycle_index: int,
        metrics: dict[str, float],
        retention_drift: float,
    ) -> CurriculumProposal:
        """Deterministic cyclic selection across Arithmetic -> Language -> Logic."""
        domain_sequence = [DomainType.ARITHMETIC, DomainType.LANGUAGE, DomainType.LOGIC]
        target = domain_sequence[(cycle_index - 1) % len(domain_sequence)]

        # Equal balanced sampling with fixed 10% replay
        ratios = {"arithmetic": 0.30, "language": 0.30, "logic": 0.30}
        ratios[target.value] = 0.40

        rationale = (
            f"Strategy [Round-Robin]: Cycle {cycle_index} statically assigns primary "
            f"focus to domain '{target.value}' based on fixed modulo scheduling."
        )

        return CurriculumProposal(
            cycle_index=cycle_index,
            strategy=CurriculumStrategy.ROUND_ROBIN,
            target_domain=target,
            intervention=InterventionType.INTERLEAVED_MULTIDOMAIN,
            sampling_ratios=ratios,
            replay_ratio=0.10,
            budget_epochs=self.default_budget_epochs,
            learning_rate=self.default_lr,
            batch_size=8,
            rationale=rationale,
            predicted_gain=0.10,
            predicted_retention_drift=+0.20,
            requires_human_approval=False,
        )

    def _select_largest_gap(
        self,
        cycle_index: int,
        metrics: dict[str, float],
        retention_drift: float,
    ) -> CurriculumProposal:
        """Myopically selects the domain with the largest deficit below target accuracy."""
        deficits: list[tuple[DomainType, float]] = []
        for d in (DomainType.ARITHMETIC, DomainType.LANGUAGE, DomainType.LOGIC):
            current_acc = metrics.get(d.value, 0.0)
            gap = max(0.0, self.target_accuracy - current_acc)
            deficits.append((d, gap))

        # Sort descending by gap
        deficits.sort(key=lambda x: x[1], reverse=True)
        weakest_domain, max_gap = deficits[0]

        # Greedy allocation: 80% to weakest domain, 10% to others, 0% replay
        ratios = {d.value: 0.10 for d in (DomainType.ARITHMETIC, DomainType.LANGUAGE, DomainType.LOGIC)}
        ratios[weakest_domain.value] = 0.80

        rationale = (
            f"Strategy [Largest Gap]: Domain '{weakest_domain.value}' has maximum "
            f"measured deficit ({max_gap:.4f}) below target {self.target_accuracy:.2f}. "
            f"Allocating 80% training mass directly to weakest capability."
        )

        return CurriculumProposal(
            cycle_index=cycle_index,
            strategy=CurriculumStrategy.LARGEST_GAP,
            target_domain=weakest_domain,
            intervention=InterventionType.FOCUSED_FINETUNE,
            sampling_ratios=ratios,
            replay_ratio=0.0,
            budget_epochs=self.default_budget_epochs,
            learning_rate=self.default_lr,
            batch_size=8,
            rationale=rationale,
            predicted_gain=min(0.25, max_gap * 0.5),
            predicted_retention_drift=+0.45,
            requires_human_approval=False,
        )

    def _select_progress_and_retention_aware(
        self,
        cycle_index: int,
        metrics: dict[str, float],
        retention_drift: float,
    ) -> CurriculumProposal:
        """Balances learning progress momentum, prerequisite readiness, and retention defense."""
        # 1. Prerequisite Checks:
        # - Language: format compliance and vocabulary must exist before complex extraction.
        # - Arithmetic: elementary column carries must be >= 0.80 before full multi-digit sequences.
        # - Logic: boolean and 2-step transitivity must be mastered before 3-step or unseen compositions.
        arith_acc = metrics.get(DomainType.ARITHMETIC.value, 0.0)
        lang_acc = metrics.get(DomainType.LANGUAGE.value, 0.0)
        logic_acc = metrics.get(DomainType.LOGIC.value, 0.0)

        # 2. Check for recent plateau in history
        recent_gains: dict[str, float] = {d.value: 0.0 for d in DomainType}
        if self.cycle_history:
            last = self.cycle_history[-1]
            target_key = last.proposal.target_domain.value
            recent_gains[target_key] = last.observed_gain

        # 3. Compute Composite Priority Score
        # Priority = Gap * Weight + Momentum_Bonus - Retention_Penalty
        domain_scores: dict[DomainType, float] = {}

        for d in (DomainType.ARITHMETIC, DomainType.LANGUAGE, DomainType.LOGIC):
            acc = metrics.get(d.value, 0.0)
            gap = max(0.0, self.target_accuracy - acc)
            score = gap * 1.0

            # Prerequisite logic: if language is at 0%, language comprehension is foundational
            if d == DomainType.LANGUAGE and acc < 0.10:
                score += 0.35  # Boost foundational communication

            # If arithmetic carry accuracy is low, elementary training has high utility
            if d == DomainType.ARITHMETIC and acc < 0.20:
                score += 0.20

            # Momentum: if domain showed positive gain recently, keep riding progress
            if recent_gains.get(d.value, 0.0) > 0.05:
                score += 0.15

            domain_scores[d] = score

        # Choose highest priority domain
        sorted_domains = sorted(domain_scores.items(), key=lambda x: x[1], reverse=True)
        selected_domain, best_score = sorted_domains[0]

        # 4. Retention-Defense Mechanism:
        # If positive drift is observed (> 0.10 nats on general prose), mandate replay buffering
        if retention_drift > 0.10:
            replay_ratio = 0.25
            intervention = InterventionType.REPLAY_STABILIZED
            ratios = {
                "arithmetic": 0.25,
                "language": 0.25,
                "logic": 0.25,
            }
            ratios[selected_domain.value] = 0.50
            retention_note = (
                f"Active positive drift ({retention_drift:+.4f} nats) triggered "
                f"protective 25% replay buffering to guard prior prose representations."
            )
            pred_drift = -0.15  # Replay expected to reduce drift
        else:
            replay_ratio = 0.10
            intervention = InterventionType.INTERLEAVED_MULTIDOMAIN
            ratios = {
                "arithmetic": 0.20,
                "language": 0.20,
                "logic": 0.20,
            }
            ratios[selected_domain.value] = 0.60
            retention_note = "Retention stable; standard 10% replay mixed."
            pred_drift = +0.05

        rationale = (
            f"Strategy [Progress & Retention Aware]: Selected '{selected_domain.value}' "
            f"(composite priority score: {best_score:.3f}, gap: {self.target_accuracy - metrics.get(selected_domain.value, 0.0):.3f}). "
            f"{retention_note}"
        )

        return CurriculumProposal(
            cycle_index=cycle_index,
            strategy=CurriculumStrategy.PROGRESS_AND_RETENTION_AWARE,
            target_domain=selected_domain,
            intervention=intervention,
            sampling_ratios=ratios,
            replay_ratio=replay_ratio,
            budget_epochs=self.default_budget_epochs,
            learning_rate=self.default_lr,
            batch_size=8,
            rationale=rationale,
            predicted_gain=0.08,
            predicted_retention_drift=pred_drift,
            requires_human_approval=False,
        )

    def record_cycle_outcome(
        self,
        proposal: CurriculumProposal,
        pre_metrics: dict[str, float],
        post_metrics: dict[str, float],
        observed_retention_drift: float,
    ) -> CycleResult:
        """Record and verify the outcome of a training cycle."""
        target = proposal.target_domain.value
        pre_acc = pre_metrics.get(target, 0.0)
        post_acc = post_metrics.get(target, 0.0)
        observed_gain = round(post_acc - pre_acc, 4)

        gain_err = round(abs(proposal.predicted_gain - observed_gain), 4)

        # Verification gate:
        # Candidate is accepted if:
        # 1. Target skill did not regress: observed_gain >= -1e-5
        # 2. Retention drift does not exceed tolerance: observed_retention_drift <= max_regression_tolerance
        is_promoted = True
        rejection_reason = None

        if observed_gain < -1e-5:
            is_promoted = False
            rejection_reason = f"Target domain {target} regressed by {observed_gain:+.4f}"
        elif observed_retention_drift > self.max_regression_tolerance:
            is_promoted = False
            rejection_reason = (
                f"Retention drift {observed_retention_drift:+.4f} exceeded tolerance "
                f"limit of {self.max_regression_tolerance:.4f}"
            )

        result = CycleResult(
            cycle_index=proposal.cycle_index,
            proposal=proposal,
            pre_metrics=pre_metrics,
            post_metrics=post_metrics,
            observed_gain=observed_gain,
            observed_retention_drift=observed_retention_drift,
            gain_prediction_error=gain_err,
            is_promoted_to_candidate=is_promoted,
            rejection_reason=rejection_reason,
        )
        self.cycle_history.append(result)
        return result
